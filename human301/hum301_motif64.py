#!/usr/bin/env python3
"""Motif64 variant of the current, complete MAA-based hum301.py.

Existing hum301_data.py caches contain 301-bp sequences and fixed train/val/test
assignments. No cache or code copy is generated by training.

Training draws a fresh uniform 256-bp crop, start 0..45 inclusive, at every
access, and applies reverse complement with probability 0.5. All positives
are used each epoch with ten distinct negatives per positive. Negatives
cycle across epochs; BCE pos_weight is ten. Optional hard-negative mining
uses training negatives only.

Architecture
------------
Input [B, 4, 256]
  -> parallel 9-/12-bp input filters (32 channels each) plus MAA residual refinement
  -> three original residual encoder blocks, lengths 128 -> 64 -> 64
     (two pooling operations: 256 -> 128 -> 64)
  -> the unchanged MAA bottleneck: MetaFormer(d=1), MetaFormer(d=2),
     Transformer, Transformer, MetaFormer(d=4), all with 128 channels and 64 positions
  -> three decoder blocks with U-Net skips, 64 -> 128 -> 256
     (the first refines without upsampling; the next two double the resolution)
  -> both original 1x1 heads; classification readout at the crop midpoint

BED-derived caches provide binary labels, not MACS3 fold-enrichment targets.
Classification loss is therefore the default; the original regression head
and MAA regression/export helpers remain, without inventing FE targets.

Full validation and test use every supplied sample. Default inference averages
probabilities from crop starts 0, 22, 23, 45 and their reverse complements.
Checkpoint selection uses validation Average Precision; the binary threshold
is selected on validation MCC, followed by the fixed test. MAA's optimizer,
scheduler, checkpointing, binary reports, confusion matrix and ROC/PR plots
are retained.
"""

