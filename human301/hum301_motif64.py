def inspect_command(args: argparse.Namespace) -> int:
    dataset_root = args.dataset_root.resolve() if args.dataset_root is not None else args.cache_path.resolve().parent
    cache_path = (
        args.cache_path.resolve()
        if args.cache_path is not None
        else dataset_root / "tf_binding_cache.npz"
    )
    if not cache_path.is_file():
        raise FileNotFoundError(f"Existing dataset cache not found: {cache_path}")
    cache = build_or_load_cache(
        dataset_root,
        cache_path,
        fe_transform=args.fe_transform,
        rebuild=args.rebuild_cache,
    )
    splits = make_splits(
        cache,
        train_chromosomes=args.train_chromosomes,
        test_chromosomes=args.test_chromosomes,
        val_fraction=args.val_fraction,
        val_block_size=args.val_block_size,
        min_split_samples_per_class=args.min_split_samples_per_class,
        val_milp_time_limit=args.val_milp_time_limit,
        balanced_evaluation=False,
    )
    print(f"Cache: {cache_path}")
    print(f"Sequences: {cache['sequences'].shape}, dtype={cache['sequences'].dtype}")
    if "fe_profiles" in cache:
        print(f"FE profiles: {cache['fe_profiles'].shape}, dtype={cache['fe_profiles'].dtype}")
    else:
        print("Targets: binary labels; no FE profiles in this BED-derived cache")
    crop_length, context_per_side = cache_geometry(cache)
    print(f"Geometry: crop {crop_length} bp from {cache['sequences'].shape[1]} bp; left context {context_per_side}, right context {cache['sequences'].shape[1] - crop_length - context_per_side}")
    labels = cache["labels"].astype(np.int64)
    for split_name, indices in splits.items():
        split_labels = labels[indices]
        print(
            f"{split_name}: n={indices.size:,}, positives={int(split_labels.sum()):,}, "
            f"negatives={int(indices.size - split_labels.sum()):,}, "
            f"chromosomes={sorted(set(cache['chromosomes'][indices].astype(str)))}"
        )
    return 0


def smoke_test_command(args: argparse.Namespace) -> int:
    seed_everything(args.seed)
    config = ModelConfig(
        sequence_length=256,
        bottleneck_length=64,
        activation=args.activation,
        classification_readout="center",
    )
    model = HumanTFBindingModel(config).to(resolve_device(args.device))
    batch_size = args.batch_size
    sequence = torch.zeros(batch_size, 4, 256, device=next(model.parameters()).device)
    random_codes = torch.randint(0, 4, (batch_size, 256), device=sequence.device)
    sequence.scatter_(1, random_codes[:, None, :], 1.0)
    centers = torch.full((batch_size,), 128, dtype=torch.long, device=sequence.device)
    with torch.no_grad():
        outputs = model(sequence, centers)
    assert model.position_embedding.shape == (1, 128, 64)
    assert outputs["classification_track"].shape == (batch_size, 256)
    assert outputs["classification_logit"].shape == (batch_size,)
    assert outputs["regression_track"].shape == (batch_size, 256)
    assert outputs["embedding"].shape == (batch_size, 64, 256)
    total, trainable = count_parameters(model)
    print("Smoke test passed.")
    print(f"classification_track: {tuple(outputs['classification_track'].shape)}")
    print(f"regression_track:     {tuple(outputs['regression_track'].shape)}")
    print(f"final_embedding:      {tuple(outputs['embedding'].shape)}")
    print(f"parameters: {total:,} total; {trainable:,} trainable")
    return 0


def evaluate_command(args: argparse.Namespace) -> int:
    cache = load_cache(args.cache)
    device = resolve_device(args.device)
    checkpoint = torch.load(args.checkpoint, map_location=device, weights_only=True)
    if checkpoint.get("cache_sha256") != sha256_file(args.cache):
        raise ValueError("Checkpoint/cache provenance mismatch; use the original cache")
    for field in ("classification_threshold", "evaluation_crop_mode", "evaluation_reverse_complement"):
        if field not in checkpoint:
            raise ValueError("Use model_for_prediction.pt with its frozen threshold and inference settings")
    if args.output_dir.exists() and any(args.output_dir.iterdir()):
        raise ValueError("Evaluation output directory must be new or empty")
    if args.eval_batch_size < 1 or args.num_workers < 0:
        raise ValueError("Invalid evaluation loader parameters")
    model = HumanTFBindingModel(ModelConfig(**checkpoint["model_config"])).to(device)
    model.load_state_dict(checkpoint["model_state"])
    indices = np.flatnonzero(cache["split"] == 2)
    dataset = TFBindingDataset(cache, indices)
    loader = make_loader(dataset, args.eval_batch_size, False, args.num_workers, device)
    criterion = nn.BCEWithLogitsLoss(pos_weight=torch.tensor(
        float(checkpoint.get("negatives_per_positive", 10)), device=device
    ))
    training_config = TrainingConfig(**checkpoint["training_config"])
    threshold = checkpoint["classification_threshold"]
    result = run_epoch(
        model, loader, device, criterion, training_config, optimizer=None,
        scaler=None, use_amp=bool(checkpoint.get("amp_enabled", False)) and device.type == "cuda",
        gradient_clip=1.0, classification_threshold=threshold,
        eval_crops=checkpoint["evaluation_crop_mode"], eval_rc=checkpoint["evaluation_reverse_complement"],
    )
    args.output_dir.mkdir(parents=True, exist_ok=True)
    payload = {"checkpoint_epoch": checkpoint["epoch"], "threshold": threshold,
               "cache_sha256": checkpoint["cache_sha256"], "test_metrics": result.classification}
    with (args.output_dir / "binary_classification_metrics.json").open("wt", encoding="utf-8") as handle:
        json.dump(payload, handle, indent=2, default=json_default)
        handle.write("\n")
    write_predictions(args.output_dir / "test_predictions.tsv", result, threshold)
    write_confusion_matrix(args.output_dir / "binary_confusion_matrix.tsv", result.classification)
    write_binary_summary(args.output_dir / "binary_classification_summary.txt", result.classification, "frozen-validation-threshold")
    write_classification_curves(args.output_dir, result, "classification")
    print_result("TEST", result, "classification")
    return 0


